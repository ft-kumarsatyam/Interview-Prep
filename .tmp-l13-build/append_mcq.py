def mcq(id: str, node: str, level: int, q: str, options: list[str], answer: int, why: str) -> dict:
    assert 10 <= len(q) <= 300, (id, len(q))
    assert 3 <= len(options) <= 4, id
    assert len({o.lower() for o in options}) == len(options), id
    assert 0 <= answer < len(options), id
    assert 10 <= len(why) <= 400, (id, len(why))
    return {"id": id, "node": node, "level": level, "q": q, "options": options, "answer": answer, "why": why}


