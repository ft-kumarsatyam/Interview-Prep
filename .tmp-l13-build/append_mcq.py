def append(path: Path, new: list[dict]) -> None:
    old = json.loads(path.read_text())
    ids = {m["id"] for m in old}
    for m in new:
        if m["id"] in ids:
            raise SystemExit(f"id already exists: {m['id']}")
    old.extend(new)
    path.write_text(json.dumps(old, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"{path.name}: +{len(new)} now {len(old)}")


